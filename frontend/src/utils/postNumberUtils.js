// Browser-compatible hash function using Web Crypto API
const generateHash = async (str) => {
    const encoder = new TextEncoder();
    const data = encoder.encode(str);
    const hashBuffer = await crypto.subtle.digest('SHA-256', data);
    const hashArray = Array.from(new Uint8Array(hashBuffer));
    return hashArray.map(b => b.toString(16).padStart(2, '0')).join('').slice(0, 8);
};

// Generate anonymous ID from IP and thread ID
export const generateAnonymousId = async (ip, threadId) => {
    const combined = `${ip}-${threadId}`;
    return await generateHash(combined);
};

