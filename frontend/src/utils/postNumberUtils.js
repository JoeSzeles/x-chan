// Format timestamp in 4chan style
export const formatTimestamp = (date) => {
    const d = new Date(date);
    const days = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
    const month = (d.getMonth() + 1).toString().padStart(2, '0');
    const day = d.getDate().toString().padStart(2, '0');
    const year = d.getFullYear().toString().slice(-2);
    const hours = d.getHours().toString().padStart(2, '0');
    const minutes = d.getMinutes().toString().padStart(2, '0');
    const seconds = d.getSeconds().toString().padStart(2, '0');
    const dayName = days[d.getDay()];
    
    return `${month}/${day}/${year}(${dayName})${hours}:${minutes}:${seconds}`;
};

// Format a post number as a quote reference
export const formatQuoteRef = (postNumber) => {
    if (!postNumber) return '';
    return `>>${formatPostNumber(postNumber)}`;
};

// Parse a quote reference
export const parseQuoteRef = (text) => {
    const match = text.match(/>>(\d+)/);
    return match ? parseInt(match[1], 10) : null;
};

