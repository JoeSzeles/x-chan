// Format user ID display
export const formatUserId = (userId, isAnonymous) => {
    if (!userId) return 'Anonymous';
    if (isAnonymous) return `ID:${userId}`;
    return `ID:${userId}`;
};

// Get country flag emoji from country code
export const getCountryFlag = (countryCode) => {
    if (!countryCode) return '';
    const codePoints = countryCode
        .toUpperCase()
        .split('')
        .map(char => 127397 + char.charCodeAt());
    return String.fromCodePoint(...codePoints);
};

// Parse quote references from text
export const parseQuoteRefs = (text) => {
    if (!text) return [];
    const matches = text.match(/>>(\d+)/g) || [];
    return matches.map(ref => {
        const number = ref.substring(2);
        return {
            fullMatch: ref,
            number: parseInt(number, 10)
        };
    });
};

